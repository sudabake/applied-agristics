package io.github.sudabake.appliedagristics.compat.botany;

import io.github.sudabake.appliedagristics.logic.CropSource;
import io.github.sudabake.appliedagristics.logic.Harvests;
import net.darkhax.botanypots.data.displaystate.*;
import net.darkhax.botanypots.data.recipes.crop.BasicCrop;
import net.darkhax.botanypots.data.recipes.crop.HarvestEntry;
import net.darkhax.botanypots.data.recipes.soil.BasicSoil;
import net.minecraft.core.BlockPos;
import net.minecraft.server.level.ServerLevel;
import net.minecraft.world.item.ItemStack;
import net.minecraft.world.level.Level;
import net.minecraft.world.level.block.state.BlockState;
import java.util.*;

/** Optional Botany Pots 13 bridge. Drops are generated by the loaded crop recipe. */
public final class BotanyCrops {
    private BotanyCrops() {}

    private static List<BasicCrop> crops(Level level) {
        return level.getRecipeManager().getRecipes().stream().filter(BasicCrop.class::isInstance)
                .map(BasicCrop.class::cast).toList();
    }

    public static List<ItemStack> seeds(Level level) {
        return crops(level).stream().flatMap(crop -> Arrays.stream(crop.getSeed().getItems()))
                .filter(stack -> !stack.isEmpty()).map(stack -> stack.copyWithCount(1)).toList();
    }

    public static CropSource find(Level level, ItemStack seed) {
        for (var crop : crops(level)) {
            if (!crop.getSeed().test(seed)) continue;
            var nativePlant = Harvests.mature(seed);
            var id = crop.getId();
            // Botany Pots 13 ships these crop records where the newer version uses derived recipes.
            if (id.getNamespace().equals("botanypots") && id.getPath().startsWith("minecraft/crop/")
                && nativePlant != null && nativePlant.getBlock() instanceof net.minecraft.world.level.block.BushBlock) continue;
            var soils = level.getRecipeManager().getRecipes().stream().filter(BasicSoil.class::isInstance)
                    .map(BasicSoil.class::cast)
                    .filter(soil -> crop.canGrowInSoil(level, BlockPos.ZERO, null, soil)
                            && soil.canGrowCrop(level, BlockPos.ZERO, null, crop))
                    .filter(soil -> soil.getIngredient().getItems().length != 0).toList();
            if (soils.isEmpty()) continue;
            var products = crop.getResults().stream().filter(entry -> entry.getChance() > 0)
                    .map(HarvestEntry::getItem).filter(stack -> !stack.isEmpty()).toList();
            var product = products.stream().filter(stack -> !ItemStack.isSameItemSameTags(stack, seed))
                    .findFirst().orElse(products.isEmpty() ? seed : products.get(0));
            return new Source(crop, soils, soils.get(0).getIngredient().getItems()[0].copyWithCount(1),
                    product.copyWithCount(1), products.stream().anyMatch(stack -> ItemStack.isSameItemSameTags(stack, seed)),
                    display(crop.getDisplayStates()));
        }
        return null;
    }

    private static BlockState display(List<DisplayState> display) {
        for (int i = display.size() - 1; i >= 0; i--) {
            var step = display.get(i);
            if (step instanceof AbstractSimpleDisplayState state) return state.getRenderState(1);
            if (step instanceof TransitionalDisplayState phases) {
                var state = display(phases.phases);
                if (state != null) return state;
            }
        }
        return null;
    }

    private record Source(BasicCrop crop, List<BasicSoil> soils, ItemStack networkSoil,
                          ItemStack product, boolean reproduces, BlockState display) implements CropSource {
        @Override public List<ItemStack> previewOutputs(ServerLevel level) {
            return crop.getResults().stream().filter(entry -> entry.getChance() > 0).map(HarvestEntry::getItem)
                    .filter(stack -> !stack.isEmpty()).map(stack -> stack.copyWithCount(1)).toList();
        }
        @Override public int ticks() { return Math.max(20, crop.getGrowthTicks()); }
        @Override public int ticks(Level level, BlockPos pos, ItemStack soil) {
            var match = soil(soil);
            if (match == null) return ticks();
            return Math.max(20, Math.round(crop.getGrowthTicks(level, pos, null, match)
                    / Math.max(.01f, 1 + match.getGrowthModifier(level, pos, null, crop))));
        }
        private BasicSoil soil(ItemStack stack) {
            return soils.stream().filter(soil -> soil.getIngredient().test(stack)).findFirst().orElse(null);
        }
        @Override public boolean acceptsSoil(ItemStack soil) { return soil(soil) != null; }
        @Override public boolean canGrow(ServerLevel level, BlockPos pos, ItemStack soil) {
            return acceptsSoil(soil) && level.getMaxLocalRawBrightness(pos.above()) >= crop.getLightLevel();
        }
        @Override public List<ItemStack> harvest(ServerLevel level, BlockPos pos, ItemStack soil) {
            return canGrow(level, pos, soil) ? harvestNetwork(level, pos) : List.of();
        }
        @Override public List<ItemStack> harvestNetwork(ServerLevel level, BlockPos pos) {
            return crop.generateDrops(new Random(level.random.nextLong()), level, pos, null);
        }
    }
}
